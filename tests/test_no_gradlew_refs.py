"""Batch 1 (T1+T2+T3) — no-new-gradlew gate (FR-TESTING-006).

Covers FR-TESTING-006 / AC-TESTING-038 + AC-TESTING-039 / TC-TESTING-038
(``TestGradlewFuzzWiring in testing/gate/gradlew-allowlist.txt``) +
TC-TESTING-039 (``python3 tests/test_no_gradlew_refs.py``):

- T1: ``testing/gate/gradlew-allowlist.txt`` names exactly the
  grandfathered paths (one repo-relative path per line); the gate test
  below is the verifier (``TestAllowlistContract``).
- T2: ``python3 tests/test_no_gradlew_refs.py`` exits 0 iff no
  ``gradlew`` literal exists outside the allowlist (single CLI entry
  via stdlib unittest); scan function
  ``find_unallowlisted(root: str, allowlist: frozenset[str]) ->
  list[str]`` returns sorted repo-relative offending paths, empty
  means pass.
- T3: verification run only — clean-tree run exits 0, a probe
  ``gradlew`` literal in a tmp tree is flagged by name (no new
  callable surface; reuses the T2 entry).

Hermetic: stdlib unittest only (``os``/``ast``/``tempfile``/
``unittest``), tmp dirs for fixtures, no network/downloads/device/
secrets, no wall-clock or socket reads.

Expected state before implementation: RED — ``testing/gate/``
allowlist does not exist, so every allowlist-dependent test fails
with a clean "allowlist absent" message; the pure-scanner tmp-tree
tests already pass.
"""

import ast
import os
import tempfile
import unittest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ALLOWLIST_RELPATH = os.path.join("testing", "gate", "gradlew-allowlist.txt")
ALLOWLIST_PATH = os.path.join(REPO_ROOT, ALLOWLIST_RELPATH)
THIS_FILE_RELPATH = os.path.join("tests", "test_no_gradlew_refs.py")

LITERAL = "gradlew"

# ASSUMPTION (scope): exclusions apply at any depth, not just top
# level, so a nested checkout/record copy can never re-enter scope.
# ASSUMPTION (bytecode): generated bytecode is never scan scope —
# ``__pycache__`` dirs are pruned at any depth and ``*.pyc``/``*.pyo``
# files are skipped, so importing this gate via
# ``python3 -m unittest`` (which writes
# ``tests/__pycache__/test_no_gradlew_refs.cpython-313.pyc``
# embedding the ``gradlew`` literal) cannot flag itself on the next run.
EXCLUDED_DIRS = frozenset(
    {".git", ".worktrees", "workflow.local", "manual-context.local", "__pycache__"}
)

# ASSUMPTION (bytecode): compiled bytecode files are generated artifacts,
# never scan scope, at any depth (see above).
EXCLUDED_SUFFIXES = frozenset({".pyc", ".pyo"})

# ASSUMPTION (scope): ``pviews/build.gradle`` is a real Gradle module
# file, not a reference — explicitly out of scope per plan/FR notes,
# so it is never scanned even though its comments name gradlew tasks.
EXCLUDED_FILE_RELPATHS = frozenset(
    {os.path.join("pviews", "build.gradle")}
)

# Modules this gate test itself may import (TC-TESTING-039 hermetic
# stdlib-only requirement, AC-TESTING-039).
STDLIB_IMPORTS = frozenset({"os", "ast", "sys", "tempfile", "unittest"})


def _normalize_entry(entry):
    """Normalize one allowlist entry to an os-native repo-rel path."""
    return entry.strip().replace("/", os.sep)


def load_allowlist(path):
    """Read allowlist file -> frozenset of normalized non-empty lines.

    ``#`` comment lines and blank lines are skipped (ASSUMPTION:
    comments keep the grandfathered list reviewable without changing
    its meaning). Raises FileNotFoundError with a clean message when
    the coder has not created the file yet (T1) — callers turn that
    into a test failure, never an import error.
    """
    entries = set()
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle.read().splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue
            entries.add(_normalize_entry(stripped))
    return frozenset(entries)


def effective_allowlist(base):
    """Add gate self-exclusions to a loaded allowlist.

    ASSUMPTION (self-exclusion): a literal-matching gate cannot name
    its own subject without flagging itself, and TC-TESTING-039
    requires a clean-tree exit 0 — so the gate test file and the
    allowlist file itself (whose ``gradlew`` shim entry contains the
    literal) are always excluded from the scan. ``find_unallowlisted``
    stays pure (no hidden skipping); the policy lives here.
    """
    return frozenset(set(base) | {ALLOWLIST_RELPATH, THIS_FILE_RELPATH})


def _is_excluded(relpath):
    """True iff a repo-relative path is outside scan scope."""
    if relpath in EXCLUDED_FILE_RELPATHS:
        return True
    basename = relpath.rsplit(os.sep, 1)[-1]
    if any(basename.endswith(suffix) for suffix in EXCLUDED_SUFFIXES):
        return True
    parts = relpath.split(os.sep)
    return any(part in EXCLUDED_DIRS for part in parts)


def _read_text(path):
    """Read a file as text, decoding with errors ignored.

    ASSUMPTION (A4): binary/undecodable bytes are decoded with
    errors ignored and then matched — ASCII ``gradlew`` bytes in a
    binary still count as a literal; an unreadable file (OSError) is
    skipped so one bad file cannot break the hermetic run.
    """
    try:
        with open(path, "rb") as handle:
            return handle.read().decode("utf-8", errors="ignore")
    except OSError:
        return None


def _is_covered(relpath, allowlist):
    """True iff an allowlist entry covers a scanned repo-rel path."""
    if relpath in allowlist:
        return True
    # ASSUMPTION (T1 path entry): an entry of the form
    # ``path::Symbol`` (e.g.
    # ``tests/test_testing_fuzz_gate.py::TestGradlewFuzzWiring``)
    # covers its file — the TC-TESTING-038 grep check requires the
    # class name to appear in the allowlist text.
    prefix = relpath + "::"
    return any(entry.startswith(prefix) for entry in allowlist)


def find_unallowlisted(root, allowlist):
    """Scan ``root`` for the ``gradlew`` literal outside ``allowlist``.

    Returns sorted repo-relative paths of files containing the
    literal that are neither excluded from scope nor covered by
    ``allowlist``. Empty means pass. Case-sensitive substring match.
    """
    normalized = frozenset(_normalize_entry(e) for e in allowlist)
    offenders = []
    for dirpath, dirnames, filenames in os.walk(root):
        # Prune excluded dirs so their subtrees are never entered.
        dirnames[:] = [d for d in dirnames if d not in EXCLUDED_DIRS]
        for filename in filenames:
            full = os.path.join(dirpath, filename)
            relpath = os.path.relpath(full, root)
            if _is_excluded(relpath):
                continue
            if _is_covered(relpath, normalized):
                continue
            text = _read_text(full)
            if text is not None and LITERAL in text:
                offenders.append(relpath)
    return sorted(offenders)


def _load_allowlist_or_fail(case):
    """Load the coder-owned allowlist or fail cleanly (red state)."""
    try:
        return load_allowlist(ALLOWLIST_PATH)
    except FileNotFoundError:
        case.fail(
            "testing/gate/gradlew-allowlist.txt absent (T1 not implemented); "
            "load path: " + ALLOWLIST_RELPATH
        )


def _write_tree(root, files):
    """Write {repo-rel path: content} under root; content may be bytes."""
    for relpath, content in files.items():
        full = os.path.join(root, *relpath.split("/"))
        parent = os.path.dirname(full)
        if parent:
            os.makedirs(parent, exist_ok=True)
        mode = "wb" if isinstance(content, bytes) else "w"
        kwargs = {} if isinstance(content, bytes) else {"encoding": "utf-8"}
        with open(full, mode, **kwargs) as handle:
            handle.write(content)


class TestAllowlistContract(unittest.TestCase):
    """T1 — the coder-owned allowlist names exactly the grandfathered set."""

    def test_allowlist_file_exists(self):
        self.assertTrue(
            os.path.isfile(ALLOWLIST_PATH),
            "testing/gate/gradlew-allowlist.txt missing (T1)",
        )

    def test_allowlist_names_fuzz_wiring(self):
        # TC-TESTING-038 Check verbatim.
        try:
            with open(ALLOWLIST_PATH, "r", encoding="utf-8") as handle:
                text = handle.read()
        except FileNotFoundError:
            self.fail(
                "testing/gate/gradlew-allowlist.txt absent (T1 not "
                "implemented); TC-TESTING-038 unsatisfiable"
            )
        self.assertIn(
            "TestGradlewFuzzWiring",
            text,
            "TestGradlewFuzzWiring in testing/gate/gradlew-allowlist.txt "
            "(TC-TESTING-038)",
        )

    def test_every_allowlist_entry_names_existing_path(self):
        allowlist = _load_allowlist_or_fail(self)
        for entry in sorted(allowlist):
            target = entry.split("::")[0]
            full = os.path.join(REPO_ROOT, target)
            self.assertTrue(
                os.path.exists(full),
                "allowlist entry names a missing path: %s (AC-TESTING-039: "
                "exact grandfathered set)" % entry,
            )

    def test_allowlist_has_no_duplicate_lines(self):
        try:
            with open(ALLOWLIST_PATH, "r", encoding="utf-8") as handle:
                lines = [
                    line.strip()
                    for line in handle.read().splitlines()
                    if line.strip() and not line.strip().startswith("#")
                ]
        except FileNotFoundError:
            self.fail(
                "testing/gate/gradlew-allowlist.txt absent (T1 not implemented)"
            )
        self.assertEqual(
            len(lines),
            len(set(lines)),
            "allowlist names the exact set — duplicates are not exact "
            "(AC-TESTING-039)",
        )


class TestScanner(unittest.TestCase):
    """T2 — pure scanner behavior on hermetic tmp trees (no repo read)."""

    def test_clean_tree_reports_no_offenders(self):
        with tempfile.TemporaryDirectory() as root:
            _write_tree(
                root,
                {
                    "src/main.py": "print('hello')\n",
                    "tests/test_ok.py": "import unittest\n",
                },
            )
            self.assertEqual(find_unallowlisted(root, frozenset()), [])

    def test_new_literal_in_code_file_is_flagged(self):
        with tempfile.TemporaryDirectory() as root:
            _write_tree(
                root,
                {
                    "scripts/run.sh": "#!/bin/sh\n./gradlew :app:build\n",
                    "src/clean.py": "x = 1\n",
                },
            )
            self.assertEqual(
                find_unallowlisted(root, frozenset()),
                [os.path.join("scripts", "run.sh")],
            )

    def test_allowlisted_path_is_not_flagged(self):
        with tempfile.TemporaryDirectory() as root:
            _write_tree(
                root, {"gradlew": "# shim\n./gradlew --help\n"}
            )
            self.assertEqual(
                find_unallowlisted(root, frozenset({"gradlew"})), []
            )
            self.assertEqual(
                find_unallowlisted(root, frozenset()),
                ["gradlew"],
            )

    def test_double_colon_entry_covers_its_file(self):
        # TC-TESTING-038 entry shape:
        # tests/test_testing_fuzz_gate.py::TestGradlewFuzzWiring
        with tempfile.TemporaryDirectory() as root:
            rel = os.path.join("tests", "test_testing_fuzz_gate.py")
            _write_tree(
                root,
                {rel.replace(os.sep, "/"): "class TestGradlewFuzzWiring: pass  # gradlew\n"},
            )
            covered = frozenset(
                {rel + "::TestGradlewFuzzWiring"}
            )
            self.assertEqual(find_unallowlisted(root, covered), [])
            self.assertEqual(find_unallowlisted(root, frozenset()), [rel])

    def test_excluded_dirs_are_never_scanned(self):
        with tempfile.TemporaryDirectory() as root:
            files = {}
            for excluded in sorted(EXCLUDED_DIRS):
                files[excluded + "/probe.txt"] = "new ./gradlew literal\n"
                files["sub/" + excluded + "/nested.txt"] = "gradlew\n"
            _write_tree(root, files)
            self.assertEqual(find_unallowlisted(root, frozenset()), [])

    def test_bytecode_artifacts_are_never_scanned(self):
        # Ambiguous-contract fix: ``python3 -m unittest`` imports this
        # gate module, generating
        # ``tests/__pycache__/test_no_gradlew_refs.cpython-313.pyc``
        # whose bytes embed the ``gradlew`` literal — the next scan must
        # stay green. ``__pycache__`` dirs (any depth) and
        # ``*.pyc``/``*.pyo`` files are excluded from scope.
        with tempfile.TemporaryDirectory() as root:
            _write_tree(
                root,
                {
                    "tests/__pycache__/test_no_gradlew_refs.cpython-313.pyc":
                        b"\x00\x00\x00gradlew\x00\x01",
                    "sub/__pycache__/nested.pyc": b"gradlew\n",
                    "top_level.pyc": b"gradlew\n",
                    "top_level.pyo": b"gradlew\n",
                    "src/clean.py": "x = 1\n",
                },
            )
            self.assertEqual(find_unallowlisted(root, frozenset()), [])

    def test_excluded_pviews_build_gradle_never_scanned(self):
        with tempfile.TemporaryDirectory() as root:
            _write_tree(
                root,
                {"pviews/build.gradle": "// ./gradlew :pviews:build\n"},
            )
            self.assertEqual(find_unallowlisted(root, frozenset()), [])

    def test_results_are_sorted_repo_relative(self):
        with tempfile.TemporaryDirectory() as root:
            _write_tree(
                root,
                {
                    "z_last.py": "gradlew\n",
                    "a_first.py": "gradlew\n",
                    "m_mid/deep.py": "gradlew\n",
                },
            )
            self.assertEqual(
                find_unallowlisted(root, frozenset()),
                ["a_first.py", os.path.join("m_mid", "deep.py"), "z_last.py"],
            )

    def test_match_is_case_sensitive(self):
        with tempfile.TemporaryDirectory() as root:
            _write_tree(
                root,
                {"src/clean.py": "Gradlew GRADLEW Gradlew\n"},
            )
            self.assertEqual(find_unallowlisted(root, frozenset()), [])

    def test_binary_bytes_do_not_crash_scanner(self):
        # A4: decode errors ignored — ASCII literal bytes still match,
        # and no exception escapes the scan.
        with tempfile.TemporaryDirectory() as root:
            _write_tree(
                root,
                {
                    "bin/blob.bin": b"\x00\xff\xfe gradlew \x00\x01",
                    "bin/clean.bin": b"\x00\xff\xfe\x01\x02",
                },
            )
            result = find_unallowlisted(root, frozenset())
            self.assertIsInstance(result, list)
            self.assertEqual(result, [os.path.join("bin", "blob.bin")])


class TestGateBehavior(unittest.TestCase):
    """T2/T3 — gate verdict on the real tree and stdlib-only discipline."""

    def test_no_unallowlisted_refs_in_tree(self):
        # T3 clean-tree run: exits 0 iff the scan is empty. Red while
        # T1's allowlist is absent or incomplete (AC-TESTING-038).
        base = _load_allowlist_or_fail(self)
        offenders = find_unallowlisted(
            REPO_ROOT, effective_allowlist(base)
        )
        self.assertEqual(
            offenders,
            [],
            "new gradlew literal(s) outside the allowlist "
            "(AC-TESTING-038): %s" % offenders,
        )

    def test_gate_module_is_stdlib_only(self):
        # AC-TESTING-039: hermetic stdlib-only gate.
        with open(os.path.abspath(__file__), "r", encoding="utf-8") as handle:
            tree = ast.parse(handle.read())
        imported = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    imported.add(alias.name.split(".")[0])
            elif isinstance(node, ast.ImportFrom):
                if node.module:
                    imported.add(node.module.split(".")[0])
        self.assertLessEqual(
            imported,
            STDLIB_IMPORTS,
            "gate test must import stdlib only (AC-TESTING-039): %s"
            % sorted(imported - STDLIB_IMPORTS),
        )

    def test_gate_policy_self_excludes_own_files(self):
        # The gate must not flag its own subject-naming file nor the
        # allowlist that names the ``gradlew`` shim (TC-TESTING-039
        # clean-tree exit 0 would otherwise be unsatisfiable).
        policy = effective_allowlist(frozenset())
        self.assertIn(THIS_FILE_RELPATH, policy)
        self.assertIn(ALLOWLIST_RELPATH, policy)

    def test_probe_literal_in_tmp_tree_fails_gate(self):
        # T3 probe run: a new literal is reported by name (non-empty =
        # gate failure analog, hermetic tmp fixture, never committed).
        with tempfile.TemporaryDirectory() as root:
            probe = os.path.join("scripts", "new_probe.sh")
            _write_tree(
                root,
                {
                    probe.replace(os.sep, "/"): "#!/bin/sh\n./gradlew :app:probe\n",
                    "src/clean.py": "x = 1\n",
                },
            )
            offenders = find_unallowlisted(root, frozenset())
            self.assertNotEqual(offenders, [])
            self.assertIn(probe, offenders)

    def test_clean_tmp_tree_passes_gate(self):
        # T3 clean analog: empty offender list means pass.
        with tempfile.TemporaryDirectory() as root:
            _write_tree(root, {"src/clean.py": "x = 1\n"})
            self.assertEqual(find_unallowlisted(root, frozenset()), [])


if __name__ == "__main__":
    unittest.main()
