#!/usr/bin/env python3
"""FR-NAV-007 T5: Route-manifest codegen — one manifest in, two artifacts out.

Reads the single-source route manifest and emits:

  <out>/route_descriptors.h — C++ RouteDescriptor table (consumed by T2
                              validateParams boundary check).
  <out>/routes.ts            — TS RouteParams map so a wrong-typed call
                              (userId: "x" vs number) is a compile error.

Interface:
  CLI `codegen.py --manifest <f> --out <dir> [--check]` exits 0 on match,
  2 on drift with unified diff on stdout.

Manifest shape (single source; extra fields ignored, not rejected):
  {"routes": [{"routeId": str, "params": [{"name": str, "type": str,
   "required": bool}]}]}
with type strings "number" | "string" | "boolean" (plus "int" | "double" |
"bool" aliases). stdlib only.
"""

import argparse
import difflib
import json
import os
import sys

HEADER_FILENAME = "route_descriptors.h"
TS_FILENAME = "routes.ts"

TS_TYPES = {
    "number": "number",
    "string": "string",
    "boolean": "boolean",
    "bool": "boolean",
    "int": "number",
    "double": "number",
}

CPP_TYPES = {
    "number": "ParamType::Double",
    "int": "ParamType::Int",
    "double": "ParamType::Double",
    "string": "ParamType::String",
    "boolean": "ParamType::Bool",
    "bool": "ParamType::Bool",
}


class CodegenError(Exception):
    """CodegenError{reason: DRIFT | SCHEMA_MISMATCH, detail: string}."""

    def __init__(self, reason, detail):
        super().__init__("%s: %s" % (reason, detail))
        self.reason = reason
        self.detail = detail


def _fail(reason, detail):
    return CodegenError(reason, detail)


def _cpp_string(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def load_manifest(manifest_path):
    try:
        with open(manifest_path, "r", encoding="utf-8") as fh:
            manifest = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        raise _fail("SCHEMA_MISMATCH",
                    "cannot parse manifest '%s': %s"
                    % (manifest_path, exc))
    if not isinstance(manifest, dict):
        raise _fail("SCHEMA_MISMATCH", "manifest root must be an object")
    return manifest


def validate_structure(manifest):
    """Structural check only. Raises CodegenError(SCHEMA_MISMATCH)."""
    if "routes" not in manifest:
        raise _fail("SCHEMA_MISMATCH", "missing required field 'routes'")
    routes = manifest["routes"]
    if not isinstance(routes, list) or not routes:
        raise _fail("SCHEMA_MISMATCH",
                    "field 'routes' must be a non-empty array")
    for i, route in enumerate(routes):
        prefix = "routes[%d]" % i
        if not isinstance(route, dict):
            raise _fail("SCHEMA_MISMATCH",
                        "%s must be an object" % prefix)
        if "routeId" not in route:
            raise _fail("SCHEMA_MISMATCH",
                        "missing required field '%s.routeId'" % prefix)
        if (not isinstance(route["routeId"], str)
                or not route["routeId"]):
            raise _fail("SCHEMA_MISMATCH",
                        "field '%s.routeId' must be a non-empty string"
                        % prefix)
        params = route.get("params", [])
        if not isinstance(params, list):
            raise _fail("SCHEMA_MISMATCH",
                        "field '%s.params' must be an array" % prefix)
        for j, param in enumerate(params):
            pfx = "%s.params[%d]" % (prefix, j)
            if not isinstance(param, dict):
                raise _fail("SCHEMA_MISMATCH",
                            "%s must be an object" % pfx)
            for field in ("name", "type"):
                if field not in param:
                    raise _fail("SCHEMA_MISMATCH",
                                 "missing required field '%s.%s'"
                                 % (pfx, field))
            if (not isinstance(param["name"], str)
                    or not param["name"]):
                raise _fail("SCHEMA_MISMATCH",
                            "field '%s.name' must be a non-empty string"
                            % pfx)
            if (not isinstance(param["type"], str)
                    or param["type"] not in CPP_TYPES):
                raise _fail("SCHEMA_MISMATCH",
                            "field '%s.type' must be one of %s"
                            % (pfx, sorted(CPP_TYPES)))
            required = param.get("required", False)
            if not isinstance(required, bool):
                raise _fail("SCHEMA_MISMATCH",
                            "field '%s.required' must be a boolean" % pfx)


def render_ts(manifest):
    lines = []
    lines.append("// Generated by toolchain/route-codegen/codegen.py — do not edit.")
    lines.append("// Single source: route manifest.")
    lines.append("export interface RouteParams {")
    for route in manifest["routes"]:
        params = route.get("params", [])
        if not params:
            lines.append("  %s: {};" % route["routeId"])
            continue
        lines.append("  %s: {" % route["routeId"])
        for param in params:
            ts_type = TS_TYPES[param["type"]]
            optional = "" if param.get("required", False) else "?"
            lines.append("    %s%s: %s;" % (param["name"], optional, ts_type))
        lines.append("  };")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_header(manifest):
    lines = []
    lines.append("// Generated by toolchain/route-codegen/codegen.py — do not edit.")
    lines.append("// Single source: route manifest.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <string>")
    lines.append("#include <vector>")
    lines.append("")
    lines.append('#include "navigation/typed_routes.h"')
    lines.append("")
    lines.append("static const std::vector<RouteDescriptor> kRouteDescriptors = {")
    for route in manifest["routes"]:
        lines.append("  RouteDescriptor{")
        lines.append("    %s," % _cpp_string(route["routeId"]))
        params = route.get("params", [])
        if not params:
            lines.append("    {},")
        else:
            lines.append("    {")
            for param in params:
                cpp_type = CPP_TYPES[param["type"]]
                req = "true" if param.get("required", False) else "false"
                lines.append("      ParamDecl{%s, %s, %s},"
                             % (_cpp_string(param["name"]), cpp_type, req))
            lines.append("    },")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def generate(manifest_path, out_dir):
    """Generate both artifacts into out_dir; return their contents."""
    manifest = load_manifest(manifest_path)
    validate_structure(manifest)
    header = render_header(manifest)
    ts = render_ts(manifest)
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, HEADER_FILENAME),
              "w", encoding="utf-8") as fh:
        fh.write(header)
    with open(os.path.join(out_dir, TS_FILENAME),
              "w", encoding="utf-8") as fh:
        fh.write(ts)
    return {"route_descriptors.h": header, "routes.ts": ts}


def _expected(manifest_path):
    manifest = load_manifest(manifest_path)
    validate_structure(manifest)
    return {
        HEADER_FILENAME: render_header(manifest),
        TS_FILENAME: render_ts(manifest),
    }


def check(manifest_path, out_dir):
    """Compare checked-in outputs against fresh generation.

    Returns 0 on match, 2 on drift (unified diff printed to stdout).
    Raises CodegenError(SCHEMA_MISMATCH) for bad manifests.
    """
    expected = _expected(manifest_path)
    drifted = False
    for filename, want in expected.items():
        path = os.path.join(out_dir, filename)
        try:
            with open(path, "r", encoding="utf-8") as fh:
                have = fh.read()
        except OSError:
            have = ""
        if have != want:
            drifted = True
            diff = difflib.unified_diff(
                have.splitlines(keepends=True),
                want.splitlines(keepends=True),
                fromfile="checked-in %s" % filename,
                tofile="generated %s" % filename,
            )
            sys.stdout.write("--- drift: %s\n" % filename)
            sys.stdout.writelines(diff)
            if not have.endswith("\n") or not want.endswith("\n"):
                sys.stdout.write("\n")
    return 2 if drifted else 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="FR-NAV-007 T5 route-manifest codegen")
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--check", action="store_true",
                        help="compare checked-in outputs, exit 2 on drift")
    args = parser.parse_args(argv)
    try:
        if args.check:
            return check(args.manifest, args.out)
        generate(args.manifest, args.out)
        return 0
    except CodegenError as exc:
        sys.stderr.write("CodegenError{reason: %s, detail: %s}\n"
                         % (exc.reason, exc.detail))
        return 1


if __name__ == "__main__":
    sys.exit(main())
