#!/usr/bin/env python3
"""BUG-LAYOUT-005 Stage 1: shape-role table codegen — one matrix in, one header out.

Reads the single-source M3 matrix (engine/layout/m3_matrix.json) and emits:

  engine/runtime/include/runtime/shape_roles.h — C++ per-component shape-role
      table (consumed by the Emit-time resolver in
      engine/runtime/src/gallery_present.cpp).

Interface:
  CLI `codegen.py [--check]` exits 0 on match, 2 on drift with a unified
  diff on stdout. Mirrors toolchain/route-codegen/codegen.py. stdlib only.

Role derivation (no invented dp): each matrix entry carries its resolved
`shape` sys token (e.g. Button `md.sys.shape.corner.full`, Card
`md.sys.shape.corner.medium`, TopAppBar `md.sys.shape.corner.none`) next to
its indirection key (`tokenTable.shape`: `md.comp.button.shape`, ...). The
role is the suffix of the resolved token after `md.sys.shape.corner.`. Only
the Stage 1 roles (none/medium/full) are emitted; components resolving to
other corners are listed in the header comment as out of scope until
Stage 2/3. dp mapping lives at the Emit call site, not here: medium → 12dp
M3 baseline (engine/layout/tokens/theme.js), none → 0 by definition,
full (pill/stadium) → half the emitted box height (geometry, not a literal).
"""

import argparse
import difflib
import json
import os
import sys

MATRIX_PATH = os.path.normpath(
    os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "..",
        "..",
        "engine",
        "layout",
        "m3_matrix.json",
    )
)
HEADER_PATH = os.path.normpath(
    os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "..",
        "..",
        "engine",
        "runtime",
        "include",
        "runtime",
        "shape_roles.h",
    )
)

STAGE1_ROLES = ("none", "medium", "full")
ROLE_ENUM = {"none": "None", "medium": "Medium", "full": "Full"}


def load_entries(matrix_path):
    try:
        with open(matrix_path, "r", encoding="utf-8") as fh:
            matrix = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError("cannot parse matrix '%s': %s" % (matrix_path, exc))
    components = matrix.get("components")
    if not isinstance(components, list):
        raise ValueError("matrix root .components must be a list")
    snapshot = matrix.get("tokenSnapshot", "unknown")
    entries = []
    deferred = []
    for comp in components:
        if not isinstance(comp, dict) or not comp.get("name"):
            continue
        shape = comp.get("shape")
        table = comp.get("tokenTable") or {}
        shape_key = table.get("shape") if isinstance(table, dict) else None
        if not isinstance(shape, str) or not shape.startswith(
            "md.sys.shape.corner."
        ):
            deferred.append(str(comp.get("name")))
            continue
        role = shape[len("md.sys.shape.corner.") :]
        if role not in STAGE1_ROLES:
            deferred.append(str(comp.get("name")))
            continue
        entries.append(
            {
                "name": comp["name"],
                "role": role,
                "shape": shape,
                "shape_key": shape_key,
            }
        )
    entries.sort(key=lambda e: e["name"])
    return snapshot, entries, sorted(set(deferred))


def render(snapshot, entries, deferred):
    lines = [
        "// Generated by toolchain/shape-codegen/codegen.py — do not edit.",
        "// Single source: engine/layout/m3_matrix.json "
        "(tokenSnapshot %s)." % snapshot,
        "// Roles are the suffix of each component's resolved `shape` sys token",
        "// (e.g. Button shape md.sys.shape.corner.full) next to its",
        "// indirection key (`tokenTable.shape`: md.comp.button.shape, ...).",
        "// Stage 1 emits only the none/medium/full roles; deferred to",
        "// Stage 2/3: %s." % (", ".join(deferred) if deferred else "none"),
        "// dp mapping lives at the Emit call site (gallery_present.cpp):",
        "// medium -> 12dp M3 baseline (engine/layout/tokens/theme.js),",
        "// none -> 0 by definition, full (pill/stadium) -> half the emitted",
        "// box height (geometry, never a baked literal). Zero-JNI: this table",
        "// is constexpr; no file reads on the emit path. Unknown components",
        "// fall closed to ShapeRole::Medium (never blank, never throws).",
        "#pragma once",
        "",
        "enum class ShapeRole {",
        "  None = 0,",
        "  Medium = 1,",
        "  Full = 2,",
        "};",
        "",
        "struct ShapeRoleEntry {",
        "  const char* component;",
        "  ShapeRole role;",
        "};",
        "",
        "static constexpr ShapeRoleEntry kShapeRoles[] = {",
    ]
    for e in entries:
        lines.append(
            '    {"%s", ShapeRole::%s},  // %s via %s'
            % (e["name"], ROLE_ENUM[e["role"]], e["shape"], e["shape_key"])
        )
    lines += [
        "};",
        "",
        "static constexpr int kShapeRoleCount = "
        "sizeof(kShapeRoles) / sizeof(kShapeRoles[0]);",
        "",
        "inline ShapeRole ShapeRoleForComponent(const char* component) {",
        "  if (component != nullptr) {",
        "    for (int i = 0; i < kShapeRoleCount; ++i) {",
        "      const char* name = kShapeRoles[i].component;",
        "      const char* want = component;",
        "      bool equal = true;",
        "      while (*name != '\\0' || *want != '\\0') {",
        "        if (*name != *want) { equal = false; break; }",
        "        ++name; ++want;",
        "      }",
        "      if (equal) return kShapeRoles[i].role;",
        "    }",
        "  }",
        "  return ShapeRole::Medium;  // Fail-closed fallback: medium baseline.",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 2 with a diff when the header drifts from the matrix",
    )
    args = parser.parse_args()
    snapshot, entries, deferred = load_entries(MATRIX_PATH)
    expected = render(snapshot, entries, deferred)
    if args.check:
        try:
            with open(HEADER_PATH, "r", encoding="utf-8") as fh:
                actual = fh.read()
        except OSError:
            actual = ""
        if actual == expected:
            return 0
        sys.stdout.write(
            "\n".join(
                difflib.unified_diff(
                    actual.splitlines(),
                    expected.splitlines(),
                    fromfile=HEADER_PATH,
                    tofile="generated",
                    lineterm="",
                )
            )
            + "\n"
        )
        return 2
    os.makedirs(os.path.dirname(HEADER_PATH), exist_ok=True)
    with open(HEADER_PATH, "w", encoding="utf-8") as fh:
        fh.write(expected)
    print("wrote %s (%d roles)" % (HEADER_PATH, len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
